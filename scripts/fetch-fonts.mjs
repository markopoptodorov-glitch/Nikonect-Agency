/* Downloads the Google Fonts the site uses into assets/fonts/ and writes a
 * local @font-face stylesheet.
 *
 *   node scripts/fetch-fonts.mjs
 *
 * Self-hosting removes two cross-origin connections and a render-blocking
 * stylesheet from the critical path, and lets the display font be preloaded
 * directly. All three families are under the SIL Open Font License.
 *
 * Cyrillic subsets are included because the Macedonian copy needs them.
 */
import { mkdir, writeFile } from 'node:fs/promises';

/* `only` restricts a family to those subsets.
 *
 * None of the three brand families ship Cyrillic, so Macedonian copy would
 * drop to whatever the system supplies. Oswald (condensed, pairs with the
 * display faces) and Inter (neutral grotesk, pairs with the body face) cover
 * it. They are declared Cyrillic-only, so unicode-range means an English
 * visitor never downloads a byte of them. */
const FAMILIES = [
  { css: 'Bebas+Neue', label: 'Bebas Neue' },
  { css: 'Big+Shoulders+Display:wght@800', label: 'Big Shoulders Display' },
  { css: 'Space+Grotesk:wght@300;500;600', label: 'Space Grotesk' },
  { css: 'Oswald:wght@600', label: 'Oswald', only: ['cyrillic', 'cyrillic-ext'] },
  { css: 'Inter:wght@300;500;600', label: 'Inter', only: ['cyrillic', 'cyrillic-ext'] },
];

/* A modern UA string is what makes Google serve woff2 rather than ttf. */
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36';

await mkdir('assets/fonts', { recursive: true });

let out = `/* Generated by scripts/fetch-fonts.mjs — do not edit by hand.
   Google Fonts, self-hosted. Each family is SIL Open Font License 1.1. */\n`;
const seen = new Set();
let count = 0;

for (const fam of FAMILIES) {
  const url = `https://fonts.googleapis.com/css2?family=${fam.css}&display=swap`;
  const res = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`${fam.label}: HTTP ${res.status}`);
  let css = await res.text();

  /* Google labels each block with a comment that PRECEDES it:
   *   / * cyrillic * / @font-face { ... }
   * Pair them explicitly. Splitting on '@font-face' instead attaches each
   * block to the next block's label, which silently fetched cyrillic-ext
   * (U+0460-052F) under the name "cyrillic" and left the U+0400-045F letters
   * Macedonian is actually written in uncovered. */
  const faces = [...css.matchAll(/\/\*\s*([a-z0-9-]+)\s*\*\/\s*@font-face\s*\{([^}]*)\}/g)];
  for (const [, subsetLabel, face] of faces) {
    const srcMatch = face.match(/src:\s*url\((https:\/\/[^)]+\.woff2)\)/);
    const weightMatch = face.match(/font-weight:\s*(\d+)/);
    if (!srcMatch) continue;

    const subset = subsetLabel;
    if (fam.only) {
      if (!fam.only.includes(subset)) continue;
    } else if (!/^(latin|latin-ext)$/.test(subset)) {
      continue;
    }

    const weight = weightMatch ? weightMatch[1] : '400';
    const slug = `${fam.label.toLowerCase().replace(/\s+/g, '-')}-${weight}-${subset}`;
    const file = `${slug}.woff2`;
    if (seen.has(file)) continue;
    seen.add(file);

    const bin = await fetch(srcMatch[1], { headers: { 'User-Agent': UA } });
    const buf = Buffer.from(await bin.arrayBuffer());
    await writeFile(`assets/fonts/${file}`, buf);
    count++;

    const range = face.match(/unicode-range:\s*([^;]+);/);
    out += `@font-face{font-family:'${fam.label}';font-style:normal;font-weight:${weight};`
         + `font-display:swap;src:url('../fonts/${file}') format('woff2');`
         + (range ? `unicode-range:${range[1].trim()};` : '')
         + `}\n`;
    console.log(`${String(Math.round(buf.length / 1024)).padStart(4)} KB  ${file}`);
  }
}

await writeFile('assets/css/fonts.css', out);
console.log(`\n${count} font files, stylesheet written to assets/css/fonts.css`);
